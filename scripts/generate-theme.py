#!/usr/bin/env python3
"""Generate platform theme files from design/tokens.json (the canonical token source).

Rules (prompt §19): tokens are the only hand-edited source; Theme.qml and Theme.kt are generated
and a drift check fails the build if they no longer match. Dynamic Material You colours are not
used, so the product identity comes from these values.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design" / "tokens.json"
QML_OUT = ROOT / "desktop" / "qml" / "Theme.qml"
KT_OUT = ROOT / "android" / "app" / "src" / "main" / "java" / "dev" / "continuity" / "app" / "ui" / "Theme.kt"

HEADER = "// GENERATED by scripts/generate-theme.py from design/tokens.json — do not edit by hand."


def qml(tokens: dict) -> str:
    mocha = tokens["themes"]["mocha"]
    latte = tokens["themes"]["latte"]
    lines = [HEADER, "pragma Singleton", "import QtQuick", "",
             "QtObject {", "    id: theme", '    property string mode: "mocha"',
             '    property var _dark: ({']
    lines += [f'        "{k}": "{v}",' for k, v in mocha.items()]
    lines += ["    })", '    property var _light: ({']
    lines += [f'        "{k}": "{v}",' for k, v in latte.items()]
    lines += ["    })", "    property var palette: mode === 'latte' ? _light : _dark"]
    for key in mocha:
        lines.append(f'    readonly property color {key}: palette["{key}"]')
    for name, value in tokens["radius"].items():
        lines.append(f"    readonly property int radius{name.capitalize()}: {value}")
    spacing = tokens["spacing"]
    for index, value in enumerate(spacing):
        lines.append(f"    readonly property int space{index}: {value}")
    lines.append(f"    readonly property int minTouch: {tokens['control']['min_touch_dp']}")
    for name, value in tokens["type"]["scale_sp"].items():
        lines.append(f"    readonly property int font{name.capitalize()}: {value}")
    lines.append(f'    readonly property string fontUi: "{tokens["type"]["family_ui"]}"')
    lines.append(f'    readonly property string fontMono: "{tokens["type"]["family_mono"]}"')
    for name, ref in tokens["state_colors"].items():
        camel = "".join(part.capitalize() for part in name.split("_"))
        lines.append(f"    readonly property color state{camel}: {ref}")
    lines += ["}", ""]
    return "\n".join(lines)


def kotlin(tokens: dict) -> str:
    mocha = tokens["themes"]["mocha"]
    latte = tokens["themes"]["latte"]
    lines = [HEADER, "package dev.continuity.app.ui", "",
             "import androidx.compose.ui.graphics.Color", "",
             "object Theme {",
             '    const val defaultMode = "' + tokens["default_theme"] + '"']
    for key, value in mocha.items():
        lines.append(f"    val {key} = Color(0xFF{value.lstrip('#')})")
    for key, value in latte.items():
        lines.append(f"    val {key}Light = Color(0xFF{value.lstrip('#')})")
    for name, value in tokens["radius"].items():
        lines.append(f"    const val radius{name.capitalize()} = {value}")
    lines += [f"    const val minTouchDp = {tokens['control']['min_touch_dp']}",
              "}", ""]
    return "\n".join(lines)


def main() -> int:
    tokens = json.loads(TOKENS.read_text())
    outputs = {QML_OUT: qml(tokens), KT_OUT: kotlin(tokens)}
    check = "--check" in sys.argv
    drift = []
    for path, content in outputs.items():
        current = path.read_text() if path.exists() else None
        if current != content:
            drift.append(str(path.relative_to(ROOT)))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if check and drift:
        print("theme drift detected in: " + ", ".join(drift), file=sys.stderr)
        print("run scripts/generate-theme.py", file=sys.stderr)
        return 1
    print(("ok: generated " if not check else "ok: no drift in ") + ", ".join(
        str(p.relative_to(ROOT)) for p in outputs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
