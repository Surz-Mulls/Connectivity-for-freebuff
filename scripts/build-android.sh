#!/usr/bin/env bash
# Reproducible debug-APK build with an unprivileged, workspace-local toolchain.
# Never uses sudo, never writes outside .toolchain/ and the Gradle cache, never creates a signing key.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

T="$ROOT/.toolchain"
SDK="$T/sdk"
JDK="$T/jdk"

if [ ! -x "$JDK/bin/java" ] || [ ! -x "$SDK/cmdline-tools/latest/bin/sdkmanager" ]; then
  echo "== bootstrapping JDK + Android cmdline-tools =="
  bash "$T/bootstrap.sh"
fi

export JAVA_HOME="$JDK"
export ANDROID_HOME="$SDK"
export ANDROID_SDK_ROOT="$SDK"
export PATH="$JAVA_HOME/bin:$ANDROID_HOME/cmdline-tools/latest/bin:$PATH"
export GRADLE_USER_HOME="$T/gradle-home"

need_platform="$("$ANDROID_HOME/cmdline-tools/latest/bin/sdkmanager" --list_installed 2>/dev/null \
  | grep -c 'platforms;android-35' || true)"
if [ "$need_platform" = "0" ]; then
  echo "== installing SDK platform + build-tools into .toolchain/sdk =="
  yes | sdkmanager "platforms;android-35" "build-tools;35.0.0" "platform-tools" >/dev/null
fi

if [ ! -d "$T/gradle-8.11.1" ]; then
  echo "== fetching Gradle 8.11.1 =="
  curl -fL -o "$T/gradle.zip" https://services.gradle.org/distributions/gradle-8.11.1-bin.zip
  unzip -q -o "$T/gradle.zip" -d "$T"
fi

printf 'sdk.dir=%s\n' "$SDK" > android/local.properties

echo "== gradle :app:assembleDebug =="
(
  cd android
  "$T/gradle-8.11.1/bin/gradle" :app:assembleDebug --no-daemon --console=plain
)

APK="$ROOT/android/app/build/outputs/apk/debug/app-debug.apk"
if [ ! -s "$APK" ]; then
  echo "FATAL: expected APK missing at $APK" >&2
  exit 1
fi

mkdir -p artifacts/android artifacts/logs
cp "$APK" artifacts/android/app-debug.apk
sha256sum artifacts/android/app-debug.apk | tee artifacts/android/app-debug.apk.sha256

APKANALYZER="$SDK/cmdline-tools/latest/bin/apkanalyzer"
if [ -x "$APKANALYZER" ]; then
  "$APKANALYZER" apk summary artifacts/android/app-debug.apk > artifacts/android/apk-summary.txt 2>&1 || true
fi
APKSIGNER="$SDK/build-tools/35.0.0/apksigner"
if [ -x "$APKSIGNER" ]; then
  "$APKSIGNER" verify --print-certs artifacts/android/app-debug.apk > artifacts/android/apk-signature.txt 2>&1 || true
fi

{
  echo "artifact: artifacts/android/app-debug.apk"
  echo "built_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "size_bytes: $(stat -c%s artifacts/android/app-debug.apk)"
  echo "sha256: $(sha256sum artifacts/android/app-debug.apk | cut -d' ' -f1)"
  echo "jdk: $("$JDK/bin/java" -version 2>&1 | head -1)"
  echo "gradle: $("$T/gradle-8.11.1/bin/gradle" --version | grep '^Gradle' | head -1)"
  echo "compile_sdk: 35"
  echo "signing: debug (debug keystore generated by the Android Gradle plugin, not release signing)"
} | tee artifacts/android/app-debug.manifest.txt

echo "OK: artifacts/android/app-debug.apk"
