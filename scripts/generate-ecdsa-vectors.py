#!/usr/bin/env python3
"""Generate shared ECDSA DER/raw test vectors for the Python and Kotlin suites.

Both the daemon (cryptography) and the Android app (JCA) must agree on the 64-byte ``r || s``
representation, so the vectors are committed and loaded by tests on both sides instead of each
language inventing its own fixtures.

Run from the repository root:  python3 scripts/generate-ecdsa-vectors.py
"""

from __future__ import annotations

import json
from pathlib import Path

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

ORDER = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
TARGETS = {
    Path("android/app/src/test/resources/ecdsa_vectors.json"),
    Path("daemon/tests/vectors/ecdsa_vectors.json"),
}


def raw_of(der: bytes) -> bytes:
    r, s = decode_dss_signature(der)
    return r.to_bytes(32, "big") + s.to_bytes(32, "big")


def main() -> int:
    key = ec.generate_private_key(ec.SECP256R1())
    valid: list[dict] = []
    short_integer = False
    leading_zero = False
    for index in range(64):
        message = f"continuity handshake vector {index}".encode()
        der = key.sign(message, ec.ECDSA(hashes.SHA256()))
        r, s = decode_dss_signature(der)
        r_len = (r.bit_length() + 7) // 8
        s_len = (s.bit_length() + 7) // 8
        short_integer = short_integer or r_len < 32 or s_len < 32
        leading_zero = leading_zero or r_len == 32 and (r >> 248) & 0x80 != 0
        valid.append({
            "message_hex": message.hex(),
            "der_hex": der.hex(),
            "raw_hex": raw_of(der).hex(),
            "r_hex": f"{r:064x}",
            "s_hex": f"{s:064x}",
        })
        if short_integer and leading_zero and len(valid) >= 8:
            break

    vectors = {
        "curve": "P-256",
        "note": "Generated by scripts/generate-ecdsa-vectors.py; raw is r||s, 32 bytes each.",
        "valid": valid,
        "invalid_der": [
            "3006020101020101ff",          # trailing garbage
            "3006020181020101",            # negative INTEGER
            "3006020100020101",            # zero INTEGER
            "300602010102",                # truncated
            "3106020101020101",            # wrong outer tag
            "3007020200010201 01".replace(" ", ""),
        ],
        "invalid_raw": [
            "00" * 64,                      # r = s = 0
            "ff" * 64,                      # r = s = 2^256-1 (above the curve order)
            "00" * 31 + "01" + "00" * 32,   # s = 0
        ],
    }
    payload = json.dumps(vectors, indent=2) + "\n"
    for target in TARGETS:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(payload)
        print(f"wrote {target} ({len(valid)} valid vectors)")
    assert order_safe(vectors), "generated vector outside the curve order"
    return 0


def order_safe(vectors: dict) -> bool:
    for vector in vectors["valid"]:
        if int(vector["r_hex"], 16) >= ORDER or int(vector["s_hex"], 16) >= ORDER:
            return False
    return True


if __name__ == "__main__":
    raise SystemExit(main())
